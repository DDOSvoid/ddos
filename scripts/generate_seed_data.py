def _fill(text: str, rng: random.Random) -> str:
    """填充模板占位符。长占位符先替换，避免 {n} 误伤 {n2}。"""
    text = text.replace("{co}", rng.choice(COMPANY_POOL))
    text = text.replace("{name}", rng.choice(PERSON_POOL))
    text = text.replace("{date}", f"2026-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}")
    text = text.replace("{days}", str(rng.randint(1, 30)))
    text = text.replace("{price}", f"{rng.randint(3, 200)}")
    text = text.replace("{eps}", f"{rng.randint(1, 50)}")
    text = text.replace("{spct}", f"{rng.randint(10, 50)}")
    for ph in ("{n4}", "{n3}", "{n2}", "{n}"):
        text = text.replace(ph, str(rng.randint(200, 50000)))
    for ph in ("{pct2}", "{pct}"):
        text = text.replace(ph, f"{rng.randint(5, 200)}%")
    return text


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate seed labeled data for BERT training")
    parser.add_argument("--per-class", type=int, default=32, help="每类生成样例数（默认 32）")
    parser.add_argument("--seed", type=int, default=42, help="随机种子（默认 42）")
    parser.add_argument("--output", default=str(OUTPUT), help="输出 JSONL 路径")
    args = parser.parse_args()

    # 校验模板与 event_types.yaml 的一致性
    all_subs = set(event_registry.sub_to_major_map.keys())
    provided = set(TEMPLATES.keys())
    missing = all_subs - provided
    extra = provided - all_subs
    if missing:
        sys.exit(f"❌ 缺少模板的子类: {sorted(missing)}")
    if extra:
        sys.exit(f"❌ 模板中存在 event_types.yaml 没有的子类: {sorted(extra)}")

    rng = random.Random(args.seed)
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    total = 0
    with open(output_path, "w", encoding="utf-8") as f:
        for sub in sorted(all_subs):
            major = event_registry.sub_to_major_map[sub]
            tpls = TEMPLATES[sub]
            for _ in range(args.per_class):
                tpl = rng.choice(tpls)
                text = f"{_fill(tpl['title'], rng)}\n{_fill(tpl['body'], rng)}"
                record = {
                    "text": text,
                    "sub_category": sub,
                    "major_category": major,
                }
                f.write(json.dumps(record, ensure_ascii=False) + "\n")
                total += 1

    print(f"✅ 生成 {total} 条种子数据 → {output_path}（{len(all_subs)} 个子类，每类 {args.per_class} 条）")


if __name__ == "__main__":
    main()
